"""Download the ILIAD intensive worksheets (Markdown/MDX) and their figures into course/.

Reads the curriculum order from upstream schedule.yaml, then for every worksheet slug
downloads both variants from https://iliad-intensive.org/downloads/<slug>/:
  <slug>-nosol.mdx -> course/worksheets/<slug>.mdx   (what agent and Julian read)
  <slug>.mdx       -> course/solutions/<slug>.mdx    (with exercise solutions)
plus every figure either variant references as `src="/uploads/..."` into
course/uploads/. Writes course/INDEX.md (days in teaching order, with local paths) and
leaves course/NOTICE.md alone.

course/solutions/ is fetched but agents must not open it unless Julian asks (rule in
CLAUDE.md, section "This Project"). This script therefore never prints solution
content, only sizes.

course/ is git-tracked on purpose: re-running this script shows upstream errata as a
plain `git diff`.

Run from the repo root: `uv run scripts/fetch_course.py` (uses the project .venv).
"""
import re
from pathlib import Path

import requests
import yaml

ROOT = Path(__file__).resolve().parent.parent
COURSE = ROOT / "course"
SCHEDULE_URL = "https://raw.githubusercontent.com/iliad-team/iliad-intensive/main/schedule.yaml"
SITE = "https://iliad-intensive.org"
FIGURE_SRC = re.compile(r'src="(/uploads/[^"]+)"')


def get(url: str) -> bytes:
    r = requests.get(url, timeout=60)
    r.raise_for_status()
    # The site is a Next.js static build that serves HTML pages for unknown paths;
    # guard so an HTML page never lands in course/ disguised as a worksheet or figure.
    ctype = r.headers.get("content-type", "")
    assert "text/html" not in ctype, f"{url} returned HTML ({ctype}), expected a file"
    return r.content


def load_days() -> list[dict]:
    """Return [{code, title, cluster, worksheets: [slug, ...]}] in teaching order."""
    schedule = yaml.safe_load(get(SCHEDULE_URL))
    days = []
    for cluster in schedule["clusters"]:
        for day in cluster["days"]:
            days.append({
                "code": day["code"],
                "title": day["title"],
                "cluster": cluster["label"],
                # A day nobody has ported yet has no worksheets key (documented upstream).
                "worksheets": day.get("worksheets") or [],
            })
    assert days, "schedule.yaml has no days"
    return days


def fetch_figures(mdx: str) -> set[str]:
    """Download every /uploads/ figure the MDX references; return their site paths."""
    srcs = set(FIGURE_SRC.findall(mdx))
    for src in srcs:
        dest = COURSE / src.lstrip("/")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(get(SITE + src))
    return srcs


def write_index(days: list[dict]) -> None:
    lines = [
        "# ILIAD Intensive: worksheets in teaching order",
        "",
        "Generated by `scripts/fetch_course.py` from upstream `schedule.yaml`; do not edit by hand.",
        "Online version of each worksheet: https://iliad-intensive.org/",
        "Versions with exercise solutions are in `solutions/`; agents open them only when Julian asks.",
        "",
        "| Day | Title | Worksheet(s) |",
        "|-----|-------|--------------|",
    ]
    for d in days:
        links = ", ".join(f"[{s}](worksheets/{s}.mdx)" for s in d["worksheets"]) or "(none ported)"
        lines.append(f"| {d['code']} | {d['title']} | {links} |")
    (COURSE / "INDEX.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    days = load_days()
    (COURSE / "worksheets").mkdir(parents=True, exist_ok=True)
    (COURSE / "solutions").mkdir(parents=True, exist_ok=True)

    n_sheets = 0
    figures: set[str] = set()
    print(f"{'day':>4}  {'slug':<40} {'nosol':>7} {'sol':>7}  figures   (sizes in chars)")
    for d in days:
        for slug in d["worksheets"]:
            nosol = get(f"{SITE}/downloads/{slug}/{slug}-nosol.mdx").decode("utf-8")
            sol = get(f"{SITE}/downloads/{slug}/{slug}.mdx").decode("utf-8")
            (COURSE / "worksheets" / f"{slug}.mdx").write_text(nosol)
            (COURSE / "solutions" / f"{slug}.mdx").write_text(sol)
            figs = fetch_figures(nosol) | fetch_figures(sol)
            figures |= figs
            n_sheets += 1
            # sol == nosol in size is expected only where upstream has no solutions
            # (e.g. debate); the size columns let a reader spot that without opening sol.
            print(f"{d['code']:>4}  {slug:<40} {len(nosol):>7} {len(sol):>7}  {len(figs)}")

    write_index(days)
    print(f"\n{len(days)} days, {n_sheets} worksheets (x2 variants), {len(figures)} figures -> {COURSE}")


if __name__ == "__main__":
    main()
